async def seed_database() -> int:
    """Idempotently insert all 20 active campus listings into the configured Postgres/Supabase database."""
    api_dir = Path(__file__).resolve().parent.parent / "apps" / "api"
    if str(api_dir) not in sys.path:
        sys.path.insert(0, str(api_dir))

    from sqlalchemy import select

    from app.dependencies import database
    from app.models.identity import Community, User
    from app.models.listing import Listing, ListingImage

    if database.async_session_factory is None:
        raise RuntimeError(
            "Database session is not configured. Ensure DATABASE_URL is set in environment or .env."
        )

    inserted = 0
    async with database.async_session_factory() as session:
        community = await session.get(Community, SEED_COMMUNITY_ID)
        if community is None:
            community = Community(
                id=SEED_COMMUNITY_ID,
                name="ADYPU Campus Community",
                type="college",
                email_domain="adypu.edu.in",
            )
            session.add(community)

        seller = await session.get(User, SEED_USER_ID)
        if seller is None:
            seller = User(
                id=SEED_USER_ID,
                auth_uid=SEED_USER_AUTH_UID,
                display_name="LOOP Campus Trader",
                area_name="ADYPU Main Block",
                geohash5="tek3x",
                is_verified=True,
                trust_score=Decimal("4.95"),
                role="user",
            )
            session.add(seller)

        await session.flush()

        for item in ACTIVE_LISTINGS:
            listing_id = uuid.uuid5(SEED_NAMESPACE, item["id_slug"])
            existing = (
                await session.execute(select(Listing).where(Listing.id == listing_id))
            ).scalar_one_or_none()
            if existing is not None:
                continue

            listing = Listing(
                id=listing_id,
                seller_id=SEED_USER_ID,
                community_id=SEED_COMMUNITY_ID,
                type=item["type"],
                category=item["category"],
                subtype=item["subtype"],
                brand=item["brand"],
                model=item["model"],
                title=item["title"],
                description=item["description"],
                condition=item["condition"],
                condition_ai=item["condition_ai"],
                condition_conf=item["condition_conf"],
                price_ask=item["price_ask"],
                price_low=item["price_low"],
                price_likely=item["price_likely"],
                price_high=item["price_high"],
                price_ai_likely=item["price_ai_likely"],
                fair_deal=item["fair_deal"],
                attributes=item["attributes"],
                area_name=item["area_name"],
                geohash5=item["geohash5"],
                status=item["status"],
                data_origin=item["data_origin"],
            )
            session.add(listing)

            for idx, img in enumerate(item["images"]):
                session.add(
                    ListingImage(
                        id=uuid.uuid5(SEED_NAMESPACE, f"{item['id_slug']}-img-{idx}"),
                        listing_id=listing_id,
                        storage_path=img["storage_path"],
                        order=idx,
                        quality_score=img["quality_score"],
                        scrub_boxes=img["scrub_boxes"],
                        scrubbed=img["scrubbed"],
                    )
                )
            inserted += 1

        await session.commit()

    print(f"Database sync complete: inserted {inserted} new active listing(s) ({len(ACTIVE_LISTINGS)} total managed).")
    return inserted


def main() -> None:
    parser = argparse.ArgumentParser(description="Verify or inject the 20 active LOOP campus listings.")
    parser.add_argument(
        "--db",
        action="store_true",
        help="Insert the 20 active listings and image metadata into Postgres / Supabase via apps/api.",
    )
    args = parser.parse_args()
    generate_seed_data()
    if args.db:
        asyncio.run(seed_database())


if __name__ == "__main__":
    main()
